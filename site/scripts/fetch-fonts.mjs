/**
 * Downloads the site's variable fonts from Google Fonts into public/fonts and
 * regenerates src/app/fonts.css.
 *
 * Run it only when you change a family, a weight range or a subset:
 *
 *   npm run fonts
 *
 * The point of committing the files is that `next build` must never depend on
 * reaching fonts.gstatic.com. `next/font/google` does that download at build
 * time, which is what broke the production build on Vercel.
 */

import dns from "node:dns";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

/* Node resolves AAAA first by default. Where IPv6 is advertised but not
 * routable — which is the case on plenty of build machines — undici sits on a
 * dead socket until it times out. This is the same failure that takes down
 * `next/font/google` during a production build. */
dns.setDefaultResultOrder("ipv4first");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
  "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36";

/** Google only serves woff2 to a browser-like User-Agent. */
const FAMILIES = [
  { family: "Oswald", slug: "oswald", query: "Oswald:wght@200..700" },
  { family: "Manrope", slug: "manrope", query: "Manrope:wght@200..800" },
  {
    family: "JetBrains Mono",
    slug: "jetbrains",
    query: "JetBrains+Mono:wght@100..800",
  },
];

/** Latin for English, Latin Extended for Azerbaijani, Cyrillic for Russian. */
const SUBSETS = new Set(["latin", "latin-ext", "cyrillic"]);

const FONT_DIR = path.join("public", "fonts");
const CSS_PATH = path.join("src", "app", "fonts.css");

const HEADER = `/*
 * Self-hosted variable fonts. GENERATED by scripts/fetch-fonts.mjs —
 * edit that script, not this file, then run \`npm run fonts\`.
 *
 * \`unicode-range\` lets the browser fetch only the subsets the rendered text
 * actually needs, so a Russian visitor never downloads the Latin Extended cut.
 */`;

async function get(url) {
  const response = await fetch(url, {
    headers: { "User-Agent": UA },
    signal: AbortSignal.timeout(60_000),
  });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText} — ${url}`);
  }
  return response;
}

async function main() {
  await mkdir(FONT_DIR, { recursive: true });

  const faces = [];

  for (const { family, slug, query } of FAMILIES) {
    const css = await (
      await get(`https://fonts.googleapis.com/css2?family=${query}&display=swap`)
    ).text();

    // Google precedes every @font-face with a /* subset */ comment.
    const blocks = css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g);

    for (const [, subset, block] of blocks) {
      if (!SUBSETS.has(subset)) continue;

      const url = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
      const range = block.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
      const weight = block.match(/font-weight:\s*([^;]+);/)?.[1]?.trim();
      if (!url || !range || !weight) {
        throw new Error(`Could not parse the ${family} ${subset} face`);
      }

      const file = `${slug}-${subset}.woff2`;
      const bytes = Buffer.from(await (await get(url)).arrayBuffer());
      await writeFile(path.join(FONT_DIR, file), bytes);

      faces.push({ family, file, range, weight, size: bytes.length });
      console.log(`${file.padEnd(28)} ${weight.padEnd(10)} ${Math.round(bytes.length / 1024)} KB`);
    }
  }

  const rules = faces.map(
    ({ family, file, range, weight }) => `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("/fonts/${file}") format("woff2");
  unicode-range: ${range};
}`,
  );

  await writeFile(CSS_PATH, `${HEADER}\n\n${rules.join("\n\n")}\n`, "utf8");

  const total = faces.reduce((sum, face) => sum + face.size, 0);
  console.log(`\n${faces.length} faces, ${Math.round(total / 1024)} KB → ${CSS_PATH}`);
}

await main();
